"""Generates sync-authentication.sh from sign_in_spec.py (A2b). Run after changing the spec, and keep the realm files in
step (KeycloakRealmContractTest checks both). Usage: python infrastructure/keycloak/generate_sync_authentication.py"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import sign_in_spec as m

flows = {alias: (desc, top, execs) for alias, desc, top, execs in m.FLOWS}
dev = json.loads(open(os.path.join(m.ROOT, "infrastructure", "keycloak", "realm-rehletshifaa.json"), "rb").read().decode("utf-8"))
staff = [u["username"] for u in dev["users"] if "rs-staff" in (u.get("realmRoles") or [])]

def q(value):  # single-quoted for bash
    return "'" + value.replace("'", "'\"'\"'") + "'"

lines = []
def build(alias):
    _, _, execs = flows[alias]
    for e in execs:
        if e[0] == "auth":
            _, provider, req, cfg = e
            lines.append(f'id=$(add_exec {alias} {provider}); set_req {alias} "$id" {req}' + (f'; add_config "$id" {q(json.dumps({"alias": cfg, "config": m.CONFIGS[cfg]}))}' if cfg else ""))
        else:
            _, sub, req = e
            lines.append(f'id=$(add_flow {alias} {sub} {q(flows[sub][0])}); set_req {alias} "$id" {req}')
            build(sub)

for alias, (desc, top, _) in flows.items():
    if top:
        lines.append(f'create_top {alias} {q(desc)}')
        build(alias)

events = json.dumps({"eventsEnabled": True, "eventsExpiration": m.EVENTS["eventsExpiration"], "enabledEventTypes": m.EVENTS["enabledEventTypes"],
                     "adminEventsEnabled": True, "adminEventsDetailsEnabled": False, "eventsListeners": ["jboss-logging"]})
realm_settings = " ".join(f"-s {k}={json.dumps(v) if isinstance(v, bool) else v}" for k, v in m.BRUTE_FORCE.items())

script = f"""#!/bin/bash
# A2b (D1 / MFA-1, owner 2026-10-14): brings an existing dev realm to the sign-in in realm-rehletshifaa.json.
# Generated by generate_sync_authentication.py from sign_in_spec.py (the realm files carry the same flows);
# run by the keycloak-sync service after the partial import.
# Idempotent: flows are built only when missing, everything else is (re)applied. Dev only.
set -euo pipefail
K=/opt/keycloak/bin/kcadm.sh
REALM="${{REALM:-rehletshifaa}}"; KC_CONFIG="${{KC_CONFIG:-/tmp/kcadm.config}}"
CFG=(--config "$KC_CONFIG" -r "$REALM")

flow_exists() {{ $K get authentication/flows "${{CFG[@]}}" --fields alias --format csv --noquotes | grep -qx "$1"; }}
create_top() {{ $K create authentication/flows "${{CFG[@]}}" -s alias="$1" -s providerId=basic-flow -s topLevel=true -s builtIn=false -s description="$2" >/dev/null; }}
add_exec() {{ $K create "authentication/flows/$1/executions/execution" "${{CFG[@]}}" -s provider="$2" -i; }}
add_flow() {{
  local flow_id; flow_id=$($K create "authentication/flows/$1/executions/flow" "${{CFG[@]}}" -s alias="$2" -s type=basic-flow -s provider=registration-page-form -s description="$3" -i)
  $K get "authentication/flows/$1/executions" "${{CFG[@]}}" --fields id,flowId --format csv --noquotes | grep ",$flow_id$" | cut -d, -f1
}}
set_req() {{
  local priority; priority=$($K get "authentication/flows/$1/executions" "${{CFG[@]}}" --fields id,priority --format csv --noquotes | grep "^$2," | cut -d, -f2)
  $K update "authentication/flows/$1/executions" "${{CFG[@]}}" -n -b "{{\\"id\\":\\"$2\\",\\"requirement\\":\\"$3\\",\\"priority\\":$priority}}"
}}
add_config() {{ $K create "authentication/executions/$1/config" "${{CFG[@]}}" -b "$2" >/dev/null; }}

# The staff marker the sign-in keys on.
$K get roles/rs-staff "${{CFG[@]}}" >/dev/null 2>&1 || $K create roles "${{CFG[@]}}" -s name=rs-staff -s {q('description=' + m.STAFF_ROLE['description'])}

if ! flow_exists rehletshifaa-browser; then
{chr(10).join('  ' + l for l in lines)}
  echo "keycloak-sync: sign-in flows built"
fi

$K update "realms/$REALM" --config "$KC_CONFIG" -s browserFlow=rehletshifaa-browser -s directGrantFlow=rehletshifaa-direct-grant-denied \\
  -s resetCredentialsFlow=rehletshifaa-reset-credentials {realm_settings}
flow_exists rehletshifaa-browser-step-up && $K delete "authentication/flows/$($K get authentication/flows "${{CFG[@]}}" --fields id,alias --format csv --noquotes | grep ",rehletshifaa-browser-step-up$" | cut -d, -f1)" "${{CFG[@]}}" && echo "keycloak-sync: old step-up flows removed"

# No password-only tokens from Keycloak's own command-line client either.
cli=$($K get clients "${{CFG[@]}}" -q clientId=admin-cli --fields id --format csv --noquotes)
$K update "clients/$cli" "${{CFG[@]}}" -s directAccessGrantsEnabled=false

# Tokens say how the person signed in (amr), which the backend checks.
web=$($K get clients "${{CFG[@]}}" -q clientId=rehletshifaa-web --fields id --format csv --noquotes)
$K get "clients/$web/protocol-mappers/models" "${{CFG[@]}}" --fields name --format csv --noquotes | grep -qx amr || \\
  $K create "clients/$web/protocol-mappers/models" "${{CFG[@]}}" -b {q(json.dumps(m.AMR_MAPPER))}

$K update events/config "${{CFG[@]}}" -b {q(events)}

for user in {" ".join(staff)}; do
  $K add-roles "${{CFG[@]}}" --uusername "$user" --rolename rs-staff 2>/dev/null || true
done
echo "keycloak-sync: second factor enforced by Keycloak for staff and for anyone who has one"
"""
out = os.path.join(m.ROOT, "infrastructure", "keycloak", "sync-authentication.sh")
open(out, "w", encoding="utf-8", newline="\n").write(script)
print("written", out, len(lines), "steps,", len(staff), "staff users")
