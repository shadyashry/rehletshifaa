"""Sound cue sheet from the authored cue dumps (the same JSON the mixer consumes), so the sheet cannot drift.

Usage: python3 -I tools/audio/cue_sheet.py mixes/cues_master_en.json mixes/cues_master_ar.json > sound_cue_sheet.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

SOURCE = {
    "elevenlabs": "ElevenLabs Sound Effects (eleven_text_to_sound_v2), generated for this film",
    "synth": "original synthesis (tools/audio/brand_sfx.py)",
}
SYNTH = {"ui_confirm", "ui_submitted", "ui_message", "ui_calendar", "transition_air", "transition_paper", "logo_signature", "roomtone_office", "roomtone_clinic"}
STEM = lambda n: "ui" if n.startswith("ui_") else "logo" if n.startswith("logo") else "transitions" if n.startswith("transition") else "foley"


def tc(t: float) -> str:
    m, s = divmod(max(0.0, t), 60)
    return f"{int(m):02d}:{s:06.3f}"


def main() -> None:
    dumps = [json.loads(Path(p).read_text()) for p in sys.argv[1:]]
    out = ["# Sound cue sheet", "",
           "Generated by `tools/audio/cue_sheet.py` from the cue dumps the mixer reads (`mixes/cues_master_{en,ar}.json`).",
           "Every cue is authored in its scene module next to the action that causes it (`ctx.sfx` / `ctx.amb`), so picture",
           "and sound move together when a language re-times a scene.", "",
           "Gain: one-shots = peak dBFS before mastering; ambience = target integrated LUFS of the bed. Pan 0 = left, 1 = right.", ""]
    for d in dumps:
        lang = d["lang"].upper()
        out += [f"## {lang} master — {d['total']:.2f} s", "", "### Narration", "", "| # | In | Out | File |", "|---|---|---|---|"]
        for i, v in enumerate(d["vo"], 1):
            out.append(f"| {i} | {tc(v['t'])} | {tc(v['t'] + v.get('dur', 0))} | `voiceover/{d['lang']}/{v['file']}` |")
        out += ["", "### Ambience beds", "", "| Scene | In | Out | Bed | Target LUFS | Fades |", "|---|---|---|---|---|---|"]
        for c in [c for c in d["cues"] if c["kind"] == "amb"]:
            out.append(f"| {c['scene']} | {tc(c['t'])} | {tc(c['end'])} | `{c['name']}` | {c['gain']} | in {c.get('fadeIn', 1.2)} s / out {c.get('fadeOut', 1.4)} s |")
        out += ["", "### Spot effects", "", "| Scene | Time | Cue | Stem | Peak dB | Pan | Length | Source |", "|---|---|---|---|---|---|---|---|"]
        for c in sorted([c for c in d["cues"] if c["kind"] == "sfx"], key=lambda c: c["t"]):
            src = SOURCE["synth"] if c["name"] in SYNTH else SOURCE["elevenlabs"]
            out.append(f"| {c['scene']} | {tc(c['t'])} | `{c['name']}` | {STEM(c['name'])} | {c['gain']} | {c.get('pan', '—')} | {str(c['dur']) + ' s' if c.get('dur') else 'full'} | {src} |")
        out += ["", "### Music", "", f"Original score `assets/audio/music/score_{d['lang']}.wav` (offset {d.get('music_offset', 0)} s), tempo-mapped so",
                "chord changes land on this language's scene starts; ducked under narration by the mixer.", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
